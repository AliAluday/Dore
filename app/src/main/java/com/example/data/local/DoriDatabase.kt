    fun initialQueueItems(venues: List<VenueEntity>): List<MerchantQueueItemEntity> {
        val sampleNames = listOf(
            "محمد الحديدي",
            "فاطمة الطائي",
            "ياسر الجبوري",
            "هبة العبيدي",
            "حسين الشمري",
            "آية الراشدي"
        )
        val items = mutableListOf<MerchantQueueItemEntity>()
        venues.forEach { venue ->
            val currentNum = venue.currentServingNumber
            val opt = venue.customOptions.firstOrNull() ?: "خدمة قياسية"
            items.add(
                MerchantQueueItemEntity(
                    venueId = venue.id,
                    ticketNumber = currentNum,
                    ticketCode = "NIN-${venue.id}-$currentNum",
                    customerName = sampleNames[venue.id % sampleNames.size],
                    customerPhone = "0770123${1000 + venue.id}",
                    selectedOption = opt,
                    status = QueueItemStatus.SERVING.name
                )
            )
            for (i in 1..venue.waitingCount) {
                val num = currentNum + i
                items.add(
                    MerchantQueueItemEntity(
                        venueId = venue.id,
                        ticketNumber = num,
                        ticketCode = "NIN-${venue.id}-$num",
                        customerName = sampleNames[(venue.id + i) % sampleNames.size],
                        customerPhone = "0780456${2000 + venue.id + i}",
                        selectedOption = venue.customOptions.getOrElse(i % venue.customOptions.size.coerceAtLeast(1)) { opt },
                        status = QueueItemStatus.WAITING.name
                    )
                )
            }
        }
        return items
    }
