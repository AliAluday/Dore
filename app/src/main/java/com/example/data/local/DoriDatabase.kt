@Database(
    entities = [
        VenueEntity::class,
        ReviewEntity::class,
        BookingEntity::class,
        MerchantQueueItemEntity::class
    ],
    version = 1,
    exportSchema = false
)
abstract class DoriDatabase : RoomDatabase() {
    abstract fun doriDao(): DoriDao

    companion object {
        @Volatile
        private var INSTANCE: DoriDatabase? = null

        fun getInstance(context: Context): DoriDatabase {
            return INSTANCE ?: synchronized(this) {
                INSTANCE ?: Room.databaseBuilder(
                    context.applicationContext,
                    DoriDatabase::class.java,
                    "dori_local.db"
                ).build().also { INSTANCE = it }
            }
        }
    }
}

